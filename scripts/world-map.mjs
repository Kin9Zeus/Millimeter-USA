// Builds src/data/world-dots.ts: a dotted world map (equirectangular) as ONE compact SVG path.
// Source: Natural Earth land polygons at 1:50m via the world-atlas package (public domain).
//   node scripts/world-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url), 'utf8'));
const land = feature(topo, topo.objects.land);

// Frame: longitudes −170…190 keep the Pacific seam out of the Americas; latitudes 78°N…56°S drop the polar caps.
export const FRAME = { lon0: -170, lon1: 190, lat0: 78, lat1: -56, width: 1000 };
const W = FRAME.width;
const H = Math.round((W * (FRAME.lat0 - FRAME.lat1)) / (FRAME.lon1 - FRAME.lon0));
const STEP = 8.5; // grid pitch in SVG units

const polygons = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
const inRing = (lon, lat, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const isLand = (lon, lat) => polygons.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)));

const parts = [];
let n = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    let lon = FRAME.lon0 + (x / W) * (FRAME.lon1 - FRAME.lon0);
    const lat = FRAME.lat0 - (y / H) * (FRAME.lat0 - FRAME.lat1);
    if (lon > 180) lon -= 360;
    if (isLand(lon, lat)) { parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`); n++; }
  }
}

const out = `// Generated by scripts/world-map.mjs from Natural Earth (1:50m land) — do not edit by hand.
// Dots are zero-length path segments drawn with round caps: stroke-width sets the dot size.
export const WORLD = { width: ${W}, height: ${H}, lon0: ${FRAME.lon0}, lon1: ${FRAME.lon1}, lat0: ${FRAME.lat0}, lat1: ${FRAME.lat1}, step: ${STEP} } as const;
export const WORLD_DOTS = '${parts.join('')}';
/** Project longitude/latitude to the map's SVG coordinates. */
export const project = (lat: number, lon: number): [number, number] => {
  const l = lon < WORLD.lon0 ? lon + 360 : lon;
  return [((l - WORLD.lon0) / (WORLD.lon1 - WORLD.lon0)) * WORLD.width, ((WORLD.lat0 - lat) / (WORLD.lat0 - WORLD.lat1)) * WORLD.height];
};
`;
writeFileSync(new URL('../src/data/world-dots.ts', import.meta.url), out);
console.log(`world-dots: ${n} dots, ${W}×${H}, ${(out.length / 1024).toFixed(1)} KB`);
